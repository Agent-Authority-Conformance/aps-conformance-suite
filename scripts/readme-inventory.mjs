// Generates the README inventory between generated markers.
//
// WHAT THIS PRINTS AND WHAT IT REFUSES TO PRINT. Automation here derives facts
// and never infers semantics. It prints what a file already declares: family
// names, target surfaces and vector counts from the integrity-checked manifest,
// paths and kinds from the reviewed cross-stack registry, and record names from
// the interop tree. It never prints a counterparty, a pin, a Mode or an
// authorship label, because every one of those is a reviewed decision a person
// wrote in an evidence document, and a generator that copied them into the front
// door would make the front door look like it had checked something.
//
// Semantic class comes from fixtures/cross-stack/index.json, never from where a
// directory sits. synthetic/ lives under cross-stack/ for historical reasons and
// is lab-authored regression material; a path-based rule would misfile it in the
// README every time it ran.
//
// Run:
//   node scripts/readme-inventory.mjs           print the block
//   node scripts/readme-inventory.mjs --write   rewrite README.md between markers
//
// tests/readme-inventory.test.mjs fails npm test when README.md has drifted.

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = join(__dirname, '..')
const README = join(REPO_ROOT, 'README.md')

export const BEGIN = '<!-- BEGIN GENERATED INVENTORY -->'
export const END = '<!-- END GENERATED INVENTORY -->'

/** The evidence document a reader should open for a family or a record. */
function evidenceDocument(dir) {
  for (const name of ['SOURCE.md', 'README.md', 'RUN.md', 'run-report.md']) {
    if (existsSync(join(dir, name))) return name
  }
  return null
}

export function buildInventory() {
  const out = []

  // 1. APS-native corpus, from the manifest that manifest-integrity.test.ts
  //    holds to the files. Nothing here is counted by walking the tree.
  const manifest = JSON.parse(readFileSync(join(REPO_ROOT, 'fixtures', 'manifest.json'), 'utf8'))
  out.push('### APS-native corpus')
  out.push('')
  out.push('| family | target surface | vectors |')
  out.push('|---|---|---|')
  for (const entry of manifest.fixtures) {
    const surface = (entry.spec_section ?? '').replace(/\|/g, '\\|')
    out.push(`| \`${entry.path}\` | ${surface} | ${entry.vector_count} |`)
  }
  out.push('')
  out.push(`${manifest.totals.fixtures} files, ${manifest.totals.vectors} vectors.`)
  out.push('')

  // 2. cross-stack, split by the reviewed kind rather than by path.
  const registry = JSON.parse(readFileSync(join(REPO_ROOT, 'fixtures', 'cross-stack', 'index.json'), 'utf8'))
  const byKind = kind => registry.entries
    .filter(e => e.kind === kind)
    .map(e => {
      const doc = evidenceDocument(join(REPO_ROOT, 'fixtures', 'cross-stack', e.path))
      return { path: e.path, doc }
    })
    .sort((a, b) => a.path.localeCompare(b.path))

  const external = byKind('external-system-family')
  out.push('### External-system families')
  out.push('')
  out.push('Artifacts produced by another party, admitted per family. Open the evidence')
  out.push('document for provenance, pins and the verification split.')
  out.push('')
  out.push('| path | evidence document |')
  out.push('|---|---|')
  for (const e of external) {
    const link = e.doc ? `[\`${e.doc}\`](fixtures/cross-stack/${e.path}/${e.doc})` : 'none'
    out.push(`| \`fixtures/cross-stack/${e.path}\` | ${link} |`)
  }
  out.push('')

  const labAuthored = byKind('lab-authored-regression')
  if (labAuthored.length > 0) {
    out.push('### Lab-authored regression fixtures')
    out.push('')
    out.push('Generated by this repository, not ingested from an external system. Listed')
    out.push('separately because they are not external-system families and are not admitted')
    out.push('under that rule.')
    out.push('')
    out.push('| path | evidence document |')
    out.push('|---|---|')
    for (const e of labAuthored) {
      const link = e.doc ? `[\`${e.doc}\`](fixtures/cross-stack/${e.path}/${e.doc})` : 'none'
      out.push(`| \`fixtures/cross-stack/${e.path}\` | ${link} |`)
    }
    out.push('')
  }

  // 3. interop records, from the tree. These are runs, not vectors.
  const interopRoot = join(REPO_ROOT, 'interop')
  const records = readdirSync(interopRoot, { withFileTypes: true })
    .filter(d => d.isDirectory())
    .map(d => d.name)
    .sort()
  out.push('### Interop run records')
  out.push('')
  out.push('Observations of an implementation at an exact revision. Each record states its')
  out.push('own mode, authorship and pins; open it to read them.')
  out.push('')
  out.push('| record | evidence document |')
  out.push('|---|---|')
  for (const name of records) {
    const doc = evidenceDocument(join(interopRoot, name))
    const link = doc ? `[\`${doc}\`](interop/${name}/${doc})` : 'none'
    out.push(`| \`interop/${name}\` | ${link} |`)
  }
  out.push('')
  out.push('Generated by `scripts/readme-inventory.mjs`. Do not edit between the markers.')

  return out.join('\n')
}

export function currentBlock(readmeText) {
  const i = readmeText.indexOf(BEGIN)
  const j = readmeText.indexOf(END)
  if (i === -1 || j === -1 || j < i) return null
  return readmeText.slice(i + BEGIN.length, j).replace(/^\n/, '').replace(/\n$/, '')
}

function main() {
  const inventory = buildInventory()
  if (!process.argv.includes('--write')) {
    console.log(inventory)
    return
  }
  const text = readFileSync(README, 'utf8')
  const i = text.indexOf(BEGIN)
  const j = text.indexOf(END)
  if (i === -1 || j === -1 || j < i) {
    console.error(`README.md is missing the generated inventory markers:\n  ${BEGIN}\n  ${END}`)
    process.exit(1)
  }
  const next = text.slice(0, i + BEGIN.length) + '\n' + inventory + '\n' + text.slice(j)
  writeFileSync(README, next)
  console.log('README.md inventory rewritten')
}

if (import.meta.url === `file://${process.argv[1]}`) main()
